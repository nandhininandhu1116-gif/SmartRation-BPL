def get_locations(column, district=None, taluk=None):
    allowed = ["district", "taluk", "village"]

    if column not in allowed:
        return []

    query = f"""
        SELECT DISTINCT TRIM({column}) AS value
        FROM beneficiaries
        WHERE {column} IS NOT NULL
        AND TRIM({column}) != ''
        AND LOWER(TRIM({column})) NOT IN ('not available','none')
    """

    params = []

    if district:
        query += " AND district = ?"
        params.append(district)

    if taluk:
        query += " AND taluk = ?"
        params.append(taluk)

    query += " ORDER BY value"

    conn = db()
    rows = conn.execute(query, params).fetchall()
    conn.close()

    return [row["value"] for row in rows]


