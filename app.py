def active_token(beneficiary_id):
    conn = db()

    row = conn.execute("""
        SELECT * FROM app_queue_records
        WHERE beneficiary_id = ?
        AND status IN ('In Queue', 'Waiting')
        ORDER BY id DESC
        LIMIT 1
    """, (beneficiary_id,)).fetchone()

    conn.close()
    return row


def generate_token_number():
    letters = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    digits = "23456789"

    conn = db()

    for _ in range(100):
        token = (
            secrets.choice(letters)
            + secrets.choice(digits)
            + secrets.choice(letters)
        )

        exists = conn.execute("""
            SELECT 1 FROM app_queue_records WHERE token = ?
            UNION
            SELECT 1 FROM queue_records WHERE token = ?
            LIMIT 1
        """, (token, token)).fetchone()

        if not exists:
            conn.close()
            return token

    conn.close()
    raise RuntimeError("Unable to generate a unique token.")


def create_token(beneficiary_id, district, taluk, village, category):
    if active_token(beneficiary_id):
        return None, tr("already_token")

    token = generate_token_number()

    conn = db()

    conn.execute("""
        INSERT INTO app_queue_records (
            beneficiary_id, token, district, taluk,
            village, category, status, created_at, ration_shop
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        beneficiary_id,
        token,
        district,
        taluk,
        village,
        category,
        "In Queue",
        datetime.now().isoformat(timespec="seconds"),
        ""
    ))

    conn.commit()
    conn.close()

    return token, tr("generated")


def queue_position(token, district, taluk, village):
    conn = db()

    rows = conn.execute("""
        SELECT token FROM app_queue_records
        WHERE district = ?
        AND taluk = ?
        AND village = ?
        AND status IN ('In Queue', 'Waiting')
        ORDER BY id
    """, (district, taluk, village)).fetchall()

    conn.close()

    for position, row in enumerate(rows, start=1):
        if row["token"] == token:
            return position

    return None

