def db():
    if not DB_PATH.exists():
        st.error("Database not found: " + str(DB_PATH))
        st.stop()

    conn = sqlite3.connect(str(DB_PATH), timeout=30)
    conn.row_factory = sqlite3.Row
    return conn


def initialize_tables():
    conn = db()

    conn.execute("""
        CREATE TABLE IF NOT EXISTS user_accounts (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT UNIQUE,
            beneficiary_id TEXT UNIQUE,
            password_hash TEXT,
            salt TEXT,
            requested_category TEXT DEFAULT 'Normal Beneficiary',
            priority_status TEXT DEFAULT 'Not Requested',
            created_at TEXT,
            mobile TEXT
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS app_queue_records (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            beneficiary_id TEXT,
            token TEXT UNIQUE,
            district TEXT,
            taluk TEXT,
            village TEXT,
            category TEXT,
            status TEXT DEFAULT 'In Queue',
            created_at TEXT,
            ration_shop TEXT
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS priority_requests (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            beneficiary_id TEXT,
            requested_category TEXT,
            reason TEXT,
            status TEXT DEFAULT 'Pending Verification',
            created_at TEXT
        )
    """)

    conn.commit()
    conn.close()


initialize_tables()

