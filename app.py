def make_hash(password, salt=None):
    salt = salt or secrets.token_hex(16)

    hashed = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode(),
        salt.encode(),
        200000
    ).hex()

    return hashed, salt


def check_password(password, stored, salt):
    calculated, _ = make_hash(password, salt)
    return secrets.compare_digest(calculated, stored)


def find_beneficiary(name, bpl):
    conn = db()

    row = conn.execute("""
        SELECT beneficiary_id, name, bpl_number,
               family_members, district, taluk,
               hobli, village, ration_shop, mobile
        FROM beneficiaries
        WHERE LOWER(TRIM(name)) = LOWER(TRIM(?))
        AND UPPER(TRIM(bpl_number)) = UPPER(TRIM(?))
        LIMIT 1
    """, (name, bpl)).fetchone()

    conn.close()
    return row


def get_beneficiary(beneficiary_id):
    conn = db()

    row = conn.execute("""
        SELECT beneficiary_id, name, bpl_number,
               family_members, district, taluk,
               hobli, village, ration_shop, mobile
        FROM beneficiaries
        WHERE beneficiary_id = ?
        LIMIT 1
    """, (beneficiary_id,)).fetchone()

    conn.close()
    return row


def get_account(username):
    conn = db()

    row = conn.execute("""
        SELECT * FROM user_accounts
        WHERE LOWER(username) = LOWER(?)
        LIMIT 1
    """, (username,)).fetchone()

    conn.close()
    return row


def create_account(name, bpl, username, password):
    beneficiary = find_beneficiary(name, bpl)

    if not beneficiary:
        return False, tr("not_found")

    conn = db()

    existing = conn.execute("""
        SELECT id FROM user_accounts
        WHERE beneficiary_id = ?
    """, (beneficiary["beneficiary_id"],)).fetchone()

    conn.close()

    if existing:
        return False, tr("account_exists")

    if get_account(username):
        return False, tr("username_exists")

    password_hash, salt = make_hash(password)

    conn = db()

    try:
        conn.execute("""
            INSERT INTO user_accounts (
                username, beneficiary_id, password_hash, salt,
                requested_category, priority_status, created_at, mobile
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            username,
            beneficiary["beneficiary_id"],
            password_hash,
            salt,
            "Normal Beneficiary",
            "Not Requested",
            datetime.now().isoformat(timespec="seconds"),
            beneficiary["mobile"]
        ))

        conn.commit()
        return True, tr("account_success")

    except sqlite3.IntegrityError:
        return False, tr("account_exists")

    finally:
        conn.close()


def login_user(username, password):
    account = get_account(username)

    if not account:
        return None

    if check_password(
        password,
        account["password_hash"],
        account["salt"]
    ):
        return get_beneficiary(account["beneficiary_id"])

    return None

