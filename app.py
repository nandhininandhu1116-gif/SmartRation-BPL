def show_priority():

    b = st.session_state.beneficiary

    st.title("🟠 " + tr("priority_heading"))
    st.write(tr("priority_description"))

    category_options = [
        tr("pregnant"),
        tr("senior"),
        tr("disability")
    ]

    category_map = {
        tr("pregnant"): "Pregnant Woman",
        tr("senior"): "Senior Citizen / Old Age",
        tr("disability"): "Person with Disability"
    }

    selected = st.selectbox(
        tr("category"),
        category_options
    )

    reason = st.text_area(tr("reason"))

    if st.button(tr("submit")):

        if not reason.strip():
            st.error(tr("reason_required"))

        else:

            success = submit_priority(
                b["beneficiary_id"],
                category_map[selected],
                reason.strip()
            )

            if success:
                st.success(tr("request_success"))
            else:
                st.warning(tr("request_pending"))

    st.subheader(tr("your_requests"))

    conn = db()

    rows = conn.execute("""
        SELECT requested_category, reason, status
        FROM priority_requests
        WHERE beneficiary_id = ?
        ORDER BY id DESC
    """, (b["beneficiary_id"],)).fetchall()

    conn.close()

    for row in rows:
        with st.container(border=True):
            st.write(row["requested_category"])
            st.write(row["reason"])
            st.write(row["status"])

